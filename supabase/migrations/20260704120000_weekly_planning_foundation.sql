DROP POLICY IF EXISTS weekly_plan_master_lists_admin_all ON public.weekly_plan_master_lists;
CREATE POLICY weekly_plan_master_lists_admin_all ON public.weekly_plan_master_lists
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.has_role(auth.uid(), 'admin'));

DROP POLICY IF EXISTS weekly_plan_master_lists_teacher_select ON public.weekly_plan_master_lists;
CREATE POLICY weekly_plan_master_lists_teacher_select ON public.weekly_plan_master_lists
  FOR SELECT TO authenticated
  USING (
    public.has_role(auth.uid(), 'teacher')
    OR public.has_role(auth.uid(), 'admin')
  );

DROP POLICY IF EXISTS weekly_plan_master_list_items_admin_all ON public.weekly_plan_master_list_items;
CREATE POLICY weekly_plan_master_list_items_admin_all ON public.weekly_plan_master_list_items
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.has_role(auth.uid(), 'admin'));

DROP POLICY IF EXISTS weekly_plan_master_list_items_teacher_select ON public.weekly_plan_master_list_items;
CREATE POLICY weekly_plan_master_list_items_teacher_select ON public.weekly_plan_master_list_items
  FOR SELECT TO authenticated
  USING (
    public.has_role(auth.uid(), 'teacher')
    OR public.has_role(auth.uid(), 'admin')
  );

DROP POLICY IF EXISTS weekly_plans_admin_all ON public.weekly_plans;
CREATE POLICY weekly_plans_admin_all ON public.weekly_plans
  FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.has_role(auth.uid(), 'admin'));

DROP POLICY IF EXISTS weekly_plans_teacher_select ON public.weekly_plans;
CREATE POLICY weekly_plans_teacher_select ON public.weekly_plans
  FOR SELECT TO authenticated
  USING (
    public.teacher_can_read_weekly_plan_row(weekly_plans.teacher_id)
  );

DROP POLICY IF EXISTS weekly_plans_teacher_insert ON public.weekly_plans;
CREATE POLICY weekly_plans_teacher_insert ON public.weekly_plans
  FOR INSERT TO authenticated
  WITH CHECK (
    weekly_plans.teacher_id = auth.uid()
    AND public.has_role(auth.uid(), 'teacher')
    AND public.teacher_can_read_assignment_row(
      weekly_plans.grade,
      weekly_plans.section,
      weekly_plans.islamic_group
    )
  );

DROP POLICY IF EXISTS weekly_plans_teacher_update ON public.weekly_plans;
CREATE POLICY weekly_plans_teacher_update ON public.weekly_plans
  FOR UPDATE TO authenticated
  USING (
    public.teacher_can_manage_weekly_plan_row(
      weekly_plans.teacher_id,
      weekly_plans.grade,
      weekly_plans.section,
      weekly_plans.islamic_group
    )
  )
  WITH CHECK (
    public.teacher_can_manage_weekly_plan_row(
      weekly_plans.teacher_id,
      weekly_plans.grade,
      weekly_plans.section,
      weekly_plans.islamic_group
    )
    AND (
      weekly_plans.teacher_id = auth.uid()
      OR public.teacher_is_lead_teacher()
    )
  );

DROP POLICY IF EXISTS weekly_plans_teacher_delete ON public.weekly_plans;
CREATE POLICY weekly_plans_teacher_delete ON public.weekly_plans
  FOR DELETE TO authenticated
  USING (
    public.teacher_can_manage_weekly_plan_row(
      weekly_plans.teacher_id,
      weekly_plans.grade,
      weekly_plans.section,
      weekly_plans.islamic_group
    )
  );

