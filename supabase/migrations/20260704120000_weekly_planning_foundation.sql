-- Weekly Planning foundation: plans, master lists, scoped RLS, workbook seed data.

-- ---------------------------------------------------------------------------
-- Master lists
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.weekly_plan_master_lists (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  list_key text NOT NULL,
  label_ar text NOT NULL DEFAULT '',
  label_en text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT weekly_plan_master_lists_list_key_check
    CHECK (trim(list_key) <> ''),
  CONSTRAINT weekly_plan_master_lists_list_key_unique UNIQUE (list_key)
);

CREATE TABLE IF NOT EXISTS public.weekly_plan_master_list_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  list_id uuid NOT NULL REFERENCES public.weekly_plan_master_lists(id) ON DELETE CASCADE,
  label_ar text NOT NULL DEFAULT '',
  label_en text NOT NULL DEFAULT '',
  sort_order integer NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT weekly_plan_master_list_items_sort_order_positive
    CHECK (sort_order > 0),
  CONSTRAINT weekly_plan_master_list_items_list_sort_unique
    UNIQUE (list_id, sort_order)
);

CREATE INDEX IF NOT EXISTS idx_weekly_plan_master_list_items_list
  ON public.weekly_plan_master_list_items (list_id, sort_order);

-- ---------------------------------------------------------------------------
-- Weekly plans
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.weekly_plans (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  teacher_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  plan_language text NOT NULL DEFAULT 'en',
  week_number integer NOT NULL,
  academic_year text NOT NULL DEFAULT '2026-2027',
  phase text,
  grade text NOT NULL,
  section text,
  islamic_group text,
  student_count integer,
  day text,
  plan_date date,
  subject text NOT NULL DEFAULT '??????? ????????? / Islamic Education',
  domain text,
  success_criterion text,
  learning_outcomes text,
  unit text,
  lesson_title text,
  uae_culture text,
  cross_curricular_real_life text,
  p21_skills jsonb NOT NULL DEFAULT '[]'::jsonb,
  key_vocabulary text,
  resources text,
  differentiation_sod jsonb NOT NULL DEFAULT '{"student_ids":[],"student_names_snapshot":[],"notes":""}'::jsonb,
  differentiation_eal jsonb NOT NULL DEFAULT '{"student_ids":[],"student_names_snapshot":[],"notes":""}'::jsonb,
  differentiation_gt jsonb NOT NULL DEFAULT '{"student_ids":[],"student_names_snapshot":[],"notes":""}'::jsonb,
  differentiation_emirati jsonb NOT NULL DEFAULT '{"student_ids":[],"student_names_snapshot":[],"notes":""}'::jsonb,
  first_period jsonb NOT NULL DEFAULT '{}'::jsonb,
  second_period jsonb NOT NULL DEFAULT '{}'::jsonb,
  teacher_reflection text,
  status text NOT NULL DEFAULT 'not_started',
  completion_percentage numeric(6, 5) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT weekly_plans_plan_language_check
    CHECK (plan_language IN ('en', 'ar')),
  CONSTRAINT weekly_plans_week_number_check
    CHECK (week_number >= 1 AND week_number <= 30),
  CONSTRAINT weekly_plans_grade_not_blank
    CHECK (trim(grade) <> ''),
  CONSTRAINT weekly_plans_section_check
    CHECK (section IS NULL OR section IN ('A', 'B', 'C', 'D', 'E', 'F', 'G', 'H')),
  CONSTRAINT weekly_plans_islamic_group_check
    CHECK (islamic_group IS NULL OR islamic_group IN ('A', 'B')),
  CONSTRAINT weekly_plans_student_count_check
    CHECK (student_count IS NULL OR (student_count >= 0 AND student_count <= 30)),
  CONSTRAINT weekly_plans_status_check
    CHECK (status IN ('not_started', 'in_progress', 'complete')),
  CONSTRAINT weekly_plans_completion_percentage_check
    CHECK (completion_percentage >= 0 AND completion_percentage <= 1)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_weekly_plans_unique_scope
  ON public.weekly_plans (teacher_id, week_number, grade, section, islamic_group)
  NULLS NOT DISTINCT;

CREATE INDEX IF NOT EXISTS idx_weekly_plans_teacher_week
  ON public.weekly_plans (teacher_id, week_number);

CREATE INDEX IF NOT EXISTS idx_weekly_plans_scope
  ON public.weekly_plans (grade, section, islamic_group);

COMMENT ON TABLE public.weekly_plans IS
  'Islamic Education weekly lesson plans per teacher/week/class scope.';

-- ---------------------------------------------------------------------------
-- updated_at trigger
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.set_weekly_plans_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_weekly_plans_updated_at ON public.weekly_plans;
CREATE TRIGGER trg_weekly_plans_updated_at
  BEFORE UPDATE ON public.weekly_plans
  FOR EACH ROW
  EXECUTE FUNCTION public.set_weekly_plans_updated_at();

-- ---------------------------------------------------------------------------
-- Scope helpers (reuse teacher_assignments authority)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.teacher_can_manage_weekly_plan_row(
  p_teacher_id uuid,
  p_grade text,
  p_section text,
  p_islamic_group text
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT public.has_role(auth.uid(), 'admin')
    OR (
      public.has_role(auth.uid(), 'teacher')
      AND (
        public.teacher_is_lead_teacher()
        OR (
          p_teacher_id = auth.uid()
          AND public.teacher_can_read_assignment_row(p_grade, p_section, p_islamic_group)
        )
      )
    );
$$;

REVOKE EXECUTE ON FUNCTION public.teacher_can_manage_weekly_plan_row(uuid, text, text, text)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.teacher_can_manage_weekly_plan_row(uuid, text, text, text)
  TO authenticated;

CREATE OR REPLACE FUNCTION public.teacher_can_read_weekly_plan_row(
  p_teacher_id uuid
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT public.has_role(auth.uid(), 'admin')
    OR (
      public.has_role(auth.uid(), 'teacher')
      AND (
        public.teacher_is_lead_teacher()
        OR p_teacher_id = auth.uid()
      )
    );
$$;

REVOKE EXECUTE ON FUNCTION public.teacher_can_read_weekly_plan_row(uuid)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.teacher_can_read_weekly_plan_row(uuid)
  TO authenticated;

